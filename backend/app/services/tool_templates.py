def format_gift_suggestions(suggestions: list) -> str:
    result = []
    for idx, item in enumerate(suggestions, 1):
        result.append(f"{idx}. {item['名称']}")
        result.append(f"   推荐理由：{item['推荐理由']}")
        result.append(f"   价格区间：{item['价格区间']}")
        result.append("")
    return "\n".join(result).strip()


def format_red_packet_recommendations(recommendations: dict) -> str:
    result = []
    
    result.append("【金额推荐】")
    for item in recommendations["金额推荐"]:
        result.append(f"{item['金额']}元 - {item['寓意']}")
    
    result.append("\n【封面语推荐】")
    for cover in recommendations["封面语"]:
        result.append(f"- {cover}")
    
    result.append("\n【留言文案推荐】")
    for message in recommendations["留言文案"]:
        result.append(f"- {message}")
    
    return "\n".join(result)


