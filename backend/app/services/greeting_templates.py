def get_greeting_template(target_group: str, style: str, format_type: str) -> list:
    group_templates = GREETING_TEMPLATES.get(target_group, {})
    style_templates = group_templates.get(style, {})
    format_templates = style_templates.get(format_type, [])
    
    return format_templates


def add_keywords_to_greeting(greeting: str, keywords: list) -> str:
    if not keywords:
        return greeting
    
    horse_keywords = ["马年", "马到", "骏马", "龙马", "千里马", "奔腾", "飞马"]
    greeting_lower = greeting.lower()
    
    for keyword in keywords:
        keyword_str = str(keyword)
        if keyword_str not in greeting_lower:
            horse_found = any(hk in greeting_lower for hk in horse_keywords)
            if horse_found:
                greeting = greeting.replace("马年", f"{keyword_str}马年", 1)
            else:
                greeting = greeting.replace("新春", f"{keyword_str}新春", 1)
    
    return greeting
